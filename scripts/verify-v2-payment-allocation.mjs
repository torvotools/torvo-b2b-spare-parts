import assert from 'node:assert/strict';
import {allocatePaymentsToBills} from '../src/v2/services/paymentAllocation.js';
const bills=[{id:'A',amount:1000},{id:'B',amount:250,allocated_credit:50}];
const payments=[{id:'P1',bill_id:'A',amount:200},{id:'P2',bill_id:'A',amount:300},{id:'P3',bill_id:'B',amount:100}];
const result=allocatePaymentsToBills(bills,payments);
assert.equal(result.bills[0].outstanding,500);
assert.equal(result.bills[1].outstanding,100);
assert.equal(result.allocations.length,3);
assert.throws(()=>allocatePaymentsToBills(bills,[payments[0],payments[0]]),/DUPLICATE/);
assert.throws(()=>allocatePaymentsToBills(bills,[{id:'P4',bill_id:'B',amount:201}]),/EXCEEDS/);
assert.throws(()=>allocatePaymentsToBills(bills,[{id:'P5',bill_id:'X',amount:1}]),/NOT FOUND/);
assert.throws(()=>allocatePaymentsToBills([{id:'A',amount:1},{id:'A',amount:1}],[]),/DUPLICATE/);
const existing=allocatePaymentsToBills([{id:'A',party_id:'D1',amount:1000,allocated_payment:300}],[{id:'NEW',bill_id:'A',party_id:'D1',amount:200}]);
assert.equal(existing.bills[0].allocated_payment,500);
assert.equal(existing.bills[0].outstanding,500);
assert.throws(()=>allocatePaymentsToBills([{id:'A',party_id:'D1',amount:100}],[{id:'BAD',bill_id:'A',party_id:'D2',amount:20}]),/PARTY MISMATCH/);
assert.throws(()=>allocatePaymentsToBills([{id:'A',party_id:'D1',amount:100}],[{id:'MISSING',bill_id:'A',amount:20}]),/PARTY MISMATCH/);
assert.throws(()=>allocatePaymentsToBills([{id:'A',amount:100,allocated_payment:101}],[]),/EXISTING ALLOCATION/);
assert.throws(()=>allocatePaymentsToBills(bills,[{id:'PENDING',bill_id:'A',status:'pending',amount:10}]),/NOT RECEIVED/);
assert.throws(()=>allocatePaymentsToBills(bills,[{id:'K1',bill_id:'A',status:'received',request_key:'same',amount:10},{id:'K2',bill_id:'A',status:'received',request_key:'same',amount:10}]),/REQUEST KEY/);
assert.equal(allocatePaymentsToBills(bills,[{id:'OK',bill_id:'A',status:'received',request_key:'unique',amount:10}]).bills[0].outstanding,990);
assert.throws(()=>allocatePaymentsToBills(bills,[{id:'ZERO',bill_id:'A',status:'received',amount:0}]),/ZERO PAYMENT/);
console.log('Payment allocation checks: PASS');
