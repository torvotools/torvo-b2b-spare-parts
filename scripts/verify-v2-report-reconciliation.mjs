import fs from 'node:fs';
const fail=m=>{console.error('FAIL '+m);process.exit(1)};
const [,,p]=process.argv;if(!p||!fs.existsSync(p))fail('usage: node scripts/verify-v2-report-reconciliation.mjs <evidence.json>');
let e;try{e=JSON.parse(fs.readFileSync(p,'utf8'))}catch{fail('invalid evidence JSON')}
for(const k of ['environment_project_id','commit_sha','captured_at_utc','accepted_transaction_refs','summary','details'])if(e[k]===undefined||e[k]===null)fail('missing '+k);
if(e.environment_project_id!=='jvmhhngjlaqrfopfavur')fail('report evidence must come from TORVO V2 STAGING');
if(!/^[a-f0-9]{40}$/i.test(e.commit_sha))fail('invalid exact commit SHA');
if(!Array.isArray(e.accepted_transaction_refs)||e.accepted_transaction_refs.length<1)fail('no accepted real staging transaction references');
if(!/^\d{4}-\d{2}-\d{2}T/.test(e.captured_at_utc))fail('captured_at_utc must be ISO timestamp');
const sales=Array.isArray(e.details.sales)?e.details.sales:fail('details.sales must be an array');
const outstanding=Array.isArray(e.details.outstanding)?e.details.outstanding:fail('details.outstanding must be an array');
if(sales.length<1)fail('sales detail is empty; real accepted transaction evidence required');
const n=x=>Number(x??0);
const salesTotal=sales.reduce((a,x)=>a+n(x.final_payable),0);
const outstandingTotal=outstanding.reduce((a,x)=>a+n(x.outstanding),0);
const eq=(a,b)=>Math.abs(n(a)-n(b))<0.005;
if(!eq(e.summary.sales_total,salesTotal))fail('summary sales_total does not reconcile to sales detail');
if(!eq(e.summary.payment_outstanding,outstandingTotal))fail('summary payment_outstanding does not reconcile to outstanding detail');
const ids=new Set(e.accepted_transaction_refs.map(String));
if(!sales.some(x=>ids.has(String(x.id??x.estimate_id))))fail('sales detail does not contain an accepted transaction reference');
console.log('PASS TORVO V2 REPORT RECONCILIATION EVIDENCE');
console.log('commit_sha='+e.commit_sha);console.log('sales_total='+salesTotal.toFixed(2));console.log('payment_outstanding='+outstandingTotal.toFixed(2));
console.log('NOTE: this validates supplied real staging evidence; it does not create transactions or independently query staging');
